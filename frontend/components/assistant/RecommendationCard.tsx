import React from 'react';
import {
  Sparkles,
  Moon,
  Sun,
  Clock,
  CheckCircle,
  Lightbulb,
  AlertCircle,
  Info,
} from 'lucide-react';
import { AIRecommendation } from '@/types';

interface RecommendationCardProps {
  recommendation: AIRecommendation;
  isDemo?: boolean;
}

export const RecommendationCard: React.FC<RecommendationCardProps> = ({
  recommendation,
  isDemo = false,
}) => {
  const getPriorityBadge = (priority: 'high' | 'medium' | 'low') => {
    switch (priority) {
      case 'high':
        return 'bg-red-50 text-red-700 border-red-200';
      case 'medium':
        return 'bg-amber-50 text-amber-700 border-amber-200';
      case 'low':
        return 'bg-blue-50 text-blue-700 border-blue-200';
    }
  };

  const getCategoryBadge = (cat: string) => {
    switch (cat) {
      case 'Circadian':
        return 'bg-purple-50 text-purple-700 border-purple-200';
      case 'Nutrition':
        return 'bg-emerald-50 text-emerald-700 border-emerald-200';
      case 'Environment':
        return 'bg-sky-50 text-sky-700 border-sky-200';
      default:
        return 'bg-slate-100 text-slate-700 border-slate-200';
    }
  };

  return (
    <div className="bg-white rounded-2xl border border-slate-200/80 p-6 shadow-sm space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 pb-5 border-b border-slate-100">
        <div className="flex items-center space-x-2.5">
          <div className="w-9 h-9 rounded-xl bg-purple-50 border border-purple-200 flex items-center justify-center text-brand-purple">
            <Sparkles className="w-5 h-5" />
          </div>
          <div>
            <h3 className="text-base font-bold text-slate-900">
              Personalised Next-Sleep Guidance
            </h3>
            <p className="text-xs text-slate-500">
              Generated by Gemini LLM from your latest EEG polysomnography architecture
            </p>
          </div>
        </div>
      </div>

      {/* Synthesis summary */}
      <div className="p-4 rounded-xl bg-slate-50 border border-slate-200/70 text-slate-700 text-xs leading-relaxed">
        <strong className="text-slate-900 block mb-1">Clinical AI Overview:</strong>
        {recommendation.summary}
      </div>

      {/* Suggested Sleep Schedule Prescription */}
      <div>
        <h4 className="text-xs font-semibold uppercase tracking-wider text-slate-400 mb-3">
          Prescribed Sleep Schedule (Next Session)
        </h4>

        <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
          <div className="p-4 rounded-xl bg-gradient-to-br from-blue-50 to-indigo-50/50 border border-blue-100 flex items-center space-x-3">
            <div className="p-2.5 rounded-lg bg-blue-600 text-white">
              <Moon className="w-4 h-4" />
            </div>
            <div>
              <span className="text-[11px] text-slate-500 block font-medium">
                Suggested Bedtime
              </span>
              <span className="text-lg font-bold text-slate-900">
                {recommendation.suggestedBedtime}
              </span>
            </div>
          </div>

          <div className="p-4 rounded-xl bg-gradient-to-br from-amber-50 to-orange-50/50 border border-amber-100 flex items-center space-x-3">
            <div className="p-2.5 rounded-lg bg-amber-500 text-white">
              <Sun className="w-4 h-4" />
            </div>
            <div>
              <span className="text-[11px] text-slate-500 block font-medium">
                Target Wake-up Time
              </span>
              <span className="text-lg font-bold text-slate-900">
                {recommendation.suggestedWakeTime}
              </span>
            </div>
          </div>

          <div className="p-4 rounded-xl bg-gradient-to-br from-purple-50 to-violet-50/50 border border-purple-100 flex items-center space-x-3">
            <div className="p-2.5 rounded-lg bg-purple-600 text-white">
              <Clock className="w-4 h-4" />
            </div>
            <div>
              <span className="text-[11px] text-slate-500 block font-medium">
                Target Rest Duration
              </span>
              <span className="text-lg font-bold text-slate-900">
                {Math.floor(recommendation.targetDurationMinutes / 60)}h{' '}
                {recommendation.targetDurationMinutes % 60}m
              </span>
            </div>
          </div>
        </div>
      </div>

      {/* Key Findings list */}
      {recommendation.keyFindings && recommendation.keyFindings.length > 0 && (
        <div>
          <h4 className="text-xs font-semibold uppercase tracking-wider text-slate-400 mb-3 flex items-center space-x-1.5">
            <CheckCircle className="w-3.5 h-3.5 text-slate-400" />
            <span>Key Polysomnography Findings</span>
          </h4>
          <ul className="space-y-2">
            {recommendation.keyFindings.map((finding, idx) => (
              <li
                key={idx}
                className="flex items-start space-x-2.5 text-xs text-slate-700 bg-white p-3 rounded-lg border border-slate-200/60"
              >
                <span className="w-1.5 h-1.5 rounded-full bg-brand-primary mt-1.5 flex-shrink-0" />
                <span>{finding}</span>
              </li>
            ))}
          </ul>
        </div>
      )}

      {/* Habit Actions */}
      <div>
        <h4 className="text-xs font-semibold uppercase tracking-wider text-slate-400 mb-3 flex items-center space-x-1.5">
          <Lightbulb className="w-3.5 h-3.5 text-slate-400" />
          <span>Targeted Behavioral Interventions</span>
        </h4>
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
          {recommendation.habits.map((habit, idx) => (
            <div
              key={idx}
              className="p-4 rounded-xl border border-slate-200/80 bg-slate-50/50 hover:bg-slate-50 transition-colors"
            >
              <div className="flex items-center justify-between gap-2 mb-2">
                <span
                  className={`text-[10px] font-semibold px-2 py-0.5 rounded-full border ${getCategoryBadge(
                    habit.category
                  )}`}
                >
                  {habit.category}
                </span>
                <span
                  className={`text-[10px] uppercase font-bold tracking-wider px-2 py-0.5 rounded border ${getPriorityBadge(
                    habit.priority
                  )}`}
                >
                  {habit.priority} priority
                </span>
              </div>
              <h5 className="text-xs font-bold text-slate-900 mb-1">{habit.title}</h5>
              <p className="text-xs text-slate-600 leading-relaxed">
                {habit.description}
              </p>
            </div>
          ))}
        </div>
      </div>

      {/* Research & Safety Disclaimer */}
      <div className="p-3.5 rounded-xl bg-blue-50/60 border border-blue-200/80 text-[11px] text-blue-900 flex items-start space-x-2.5">
        <Info className="w-4 h-4 text-blue-600 flex-shrink-0 mt-0.5" />
        <p className="leading-relaxed">
          <strong>Research Disclaimer:</strong> This application is developed for MCA academic
          research purposes. AI recommendations are generated by an LLM based on EEG feature
          extractions and do not substitute clinical medical advice or diagnosis from a board-certified
          sleep physician.
        </p>
      </div>
    </div>
  );
};

